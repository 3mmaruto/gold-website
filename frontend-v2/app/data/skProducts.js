export function getSkProduct(locale, slug) {
  const safeLocale = locale === "en" ? "en" : "ar";
  const model = localized[safeLocale][slug];
  if (!model) return null;

  return {
    slug,
    model: slug.toUpperCase(),
    locale: safeLocale,
    ...localized[safeLocale].common,
    ...model,
    image: assets[slug],
    dimensionsImage: assets.dimensions,
    hydronicImage: assets.hydronic,
  };
}

export function getSkProductProfiles(locale) {
  return ["sk22", "sk30"].map((slug) => getSkProduct(locale, slug));
}

export function isSkProductSlug(slug) {
  return slug === "sk22" || slug === "sk30";
}
