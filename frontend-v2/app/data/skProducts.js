export function getSkProduct(locale, slug) {
  const safeLocale = locale === "en" ? "en" : "ar";
  const product = localized[safeLocale][slug];
  if (!product) return null;

  const family = product.family;
  return {
    slug,
    locale: safeLocale,
    ...baseCommon[safeLocale],
    ...familyCommon[safeLocale][family],
    ...product,
    image: productAssets[slug],
    dimensionsImage: family === "r290" ? sharedAssets.r290Lineup : sharedAssets.r410aDimensions,
    hydronicImage: sharedAssets.hydronic,
  };
}

export function getSkProductProfiles(locale) {
  return slugs.map((slug) => getSkProduct(locale, slug));
}

export function isSkProductSlug(slug) {
  return slugs.includes(slug);
}
